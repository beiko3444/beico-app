function normalizeProductText(value) {
  return String(value || '')
    .toLocaleLowerCase('ko-KR')
    .replace(/beiko|xtracker|엑스트래커|상품\s*그룹|정품/g, '')
    .replace(/[^0-9a-z가-힣]+/g, '')
}

const NORMALIZED_NAVER_PRODUCTS = VERIFIED_NAVER_PRODUCTS.map(([pattern, productNo]) => ({
  pattern: normalizeProductText(pattern),
  url: `https://smartstore.naver.com/xtr/products/${productNo}`,
}))

export function getNaverProductUrl(groupName, productNames = []) {
  const searchableNames = [groupName, ...productNames]
    .map(normalizeProductText)
    .filter(Boolean)

  for (const entry of NORMALIZED_NAVER_PRODUCTS) {
    const matched = searchableNames.some((name) => (
      name.includes(entry.pattern) || (name.length >= 8 && entry.pattern.includes(name))
    ))
    if (matched) return entry.url
  }

  return null
}

export const NAVER_PRODUCT_LINKS = NORMALIZED_NAVER_PRODUCTS.map(({ url }) => url)
